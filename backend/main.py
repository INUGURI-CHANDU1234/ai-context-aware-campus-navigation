from fastapi import FastAPI, WebSocket, WebSocketDisconnect
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel
from typing import Optional

from agents.coordinator_agent import coordinator


app = FastAPI(title="AI Campus Navigation API")


# ---------------------------------------------------------
# CORS
# ---------------------------------------------------------

app.add_middleware(
    CORSMiddleware,
    allow_origins=[
    "http://localhost:5173",
    "http://127.0.0.1:5173",
    "http://localhost:4173",
    "http://127.0.0.1:4173",
],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)


# ---------------------------------------------------------
# Request model
# ---------------------------------------------------------

class RouteRequest(BaseModel):
    start: str
    destination: str

    crowd: str = "LOW"
    blocked_path: str = "none"
    active_area: str = "central"

    # Optional frontend fields
    path_condition: Optional[str] = None


# ---------------------------------------------------------
# Health check
# ---------------------------------------------------------

@app.get("/api/health")
def health():
    return {
        "status": "ok",
        "service": "AI Campus Navigation API",
        "stage": 6,
        "mode": "multi-agent dynamic routing",
    }


# ---------------------------------------------------------
# Main routing API
# ---------------------------------------------------------

@app.post("/api/route")
def calculate_route(request: RouteRequest):

    blocked = request.blocked_path

    # Convert frontend path-condition values into
    # the internal blocked_path representation.
    if request.path_condition:
        condition = request.path_condition.lower()

        if condition not in ["none", "all paths open", "all road segments open"]:
            blocked = request.path_condition

    state = {
        "start": request.start,
        "destination": request.destination,
        "crowd": request.crowd.upper(),
        "blocked_path": blocked,
        "active_area": request.active_area,
    }

    # Run the complete multi-agent system
    result = coordinator(state)

    navigation = result.get("navigation", {})
    decision = result.get("decision", {})

    # Extract route generated by A*
    path = navigation.get("path", [])
    cost = navigation.get("cost")
    segments = navigation.get("segments", [])
    path_coords = navigation.get("path_coords", [])

    return {
        # Basic route information
        "path": path,
        "cost": cost,
        "segments": segments,
        "path_coords": path_coords,
        "network_type": navigation.get(
            "network_type",
            "pedestrian_road_segments"
        ),

        # Request information
        "request": result.get("request", {}),

        # Multi-agent outputs
        "context": result.get("context", {}),
        "crowd": result.get("crowd", {}),
        "obstacle": result.get("obstacle", {}),
        "navigation": navigation,
        "decision": decision,
        "coordinator": result.get("coordinator", {}),

        # Convenient frontend status
        "status": navigation.get("status", "no_route"),

        # Human-readable route
        "route_found": bool(path),
        "route": path,

        # Explainable AI
        "explanation": {
            "summary": decision.get("summary"),
            "action": decision.get("action"),
            "confidence": decision.get("confidence"),
            "risk_score": decision.get("risk_score"),
            "factors": decision.get("factors", []),
        },
    }


# ---------------------------------------------------------
# Real-time context WebSocket
# ---------------------------------------------------------

@app.websocket("/ws/context")
async def context_websocket(websocket: WebSocket):

    await websocket.accept()

    try:
        while True:

            data = await websocket.receive_json()

            state = {
                "start": data.get("start", "engineering"),
                "destination": data.get("destination", "auditorium"),
                "crowd": data.get("crowd", "LOW").upper(),
                "blocked_path": data.get("blocked_path", "none"),
                "active_area": data.get("active_area", "central"),
            }

            result = coordinator(state)

            navigation = result.get("navigation", {})
            decision = result.get("decision", {})

            await websocket.send_json({
                "type": "context_update",

                "context": result.get("context", {}),
                "crowd": result.get("crowd", {}),
                "obstacle": result.get("obstacle", {}),

                "navigation": navigation,

                "decision": decision,

                "route": navigation.get("path", []),
                "cost": navigation.get("cost"),
                "segments": navigation.get("segments", []),
                "path_coords": navigation.get("path_coords", []),

                "status": navigation.get(
                    "status",
                    "no_route"
                ),
            })

    except WebSocketDisconnect:
        pass